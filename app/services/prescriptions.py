from pathlib import Path
from uuid import UUID, uuid4

from sqlalchemy import select

from app.core.config import get_settings
from app.models.prescriptions import Prescription

MAX_PRESCRIPTION_BYTES = 5 * 1024 * 1024
ALLOWED_SIGNATURES = {
    "application/pdf": (b"%PDF-", ".pdf"),
    "image/png": (b"\x89PNG\r\n\x1a\n", ".png"),
    "image/jpeg": (b"\xff\xd8\xff", ".jpg"),
}


def latest_prescriptions_for_products(db, customer_id: UUID, product_ids: list[UUID]) -> dict[UUID, Prescription]:
    if not product_ids:
        return {}
    rows = db.scalars(
        select(Prescription)
        .where(Prescription.customer_id == customer_id, Prescription.product_id.in_(product_ids))
        .order_by(Prescription.created_at.desc(), Prescription.id.desc())
    ).all()
    latest: dict[UUID, Prescription] = {}
    for row in rows:
        latest.setdefault(row.product_id, row)
    return latest


def validate_document(content_type: str | None, data: bytes) -> tuple[str, str]:
    if len(data) > MAX_PRESCRIPTION_BYTES:
        raise ValueError("Prescription files must be 5 MB or smaller")
    if not data:
        raise ValueError("Choose a PDF, PNG, or JPEG prescription file")
    document = ALLOWED_SIGNATURES.get(content_type or "")
    if document is None or not data.startswith(document[0]):
        raise ValueError("The file must be a valid PDF, PNG, or JPEG")
    return content_type, document[1]


def write_private_document(data: bytes, extension: str) -> tuple[str, Path]:
    directory = get_settings().prescription_storage_path
    directory.mkdir(parents=True, exist_ok=True)
    storage_key = f"{uuid4().hex}{extension}"
    path = directory / storage_key
    with path.open("xb") as stored:
        stored.write(data)
    return storage_key, path


def private_document_path(prescription: Prescription) -> Path:
    # Keys are generated by this service; the user supplied filename is never used.
    path = get_settings().prescription_storage_path / prescription.storage_key
    return path


def remove_private_document(path: Path) -> None:
    try:
        path.unlink(missing_ok=True)
    except OSError:
        pass
